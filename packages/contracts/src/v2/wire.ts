export type WireSchemaName = keyof typeof WIRE_SCHEMAS;
export function getWireSchema(name: string): z.ZodTypeAny {
  if (!Object.hasOwn(WIRE_SCHEMAS, name)) throw new Error(`Unknown wire schema: ${name}`);
  return WIRE_SCHEMAS[name as WireSchemaName];
}
